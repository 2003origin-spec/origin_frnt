async function fakeR2Up(): Promise<boolean> {
  const endpoint = process.env.R2_ENDPOINT;
  if (!endpoint) return false;
  try {
    await fetch(endpoint, { method: "OPTIONS", signal: AbortSignal.timeout(1000) });
    return true;
  } catch {
    return false;
  }
}

const skip = dbConfigured() ? false : "USER_DATABASE_URL not set";

// Loaded in the test (see the header): these pull in src/server/incidents.ts.
let createTrack: typeof import("@/server/music/admin").createTrack;
let deleteTrack: typeof import("@/server/music/admin").deleteTrack;
let listAdminTracks: typeof import("@/server/music/admin").listAdminTracks;
let presignMusicUpload: typeof import("@/server/music/admin").presignMusicUpload;
let publishTrack: typeof import("@/server/music/admin").publishTrack;
let retireTrack: typeof import("@/server/music/admin").retireTrack;
let updateTrack: typeof import("@/server/music/admin").updateTrack;
let handleMusicApi: typeof import("@/server/music/student-api").handleMusicApi;

const adminId = makeId("user_music_admin");
const studentId = makeId("user_music_student");
const otherId = makeId("user_music_other");

function pool() {
  const p = getUserPostgresPool();
  if (!p) throw new Error("no pool");
  return p;
}

async function expectCode(promise: Promise<unknown>, code: string): Promise<void> {
  try {
    await promise;
  } catch (error) {
    assert.ok(error instanceof MusicError, `expected MusicError ${code}, got ${String(error)}`);
    assert.equal(error.code, code);
    return;
  }
  assert.fail(`expected ${code}`);
}

/** A fake m4a: an MP4 `ftyp` box then a byte pattern. Not playable, but passes the type check. */
function fakeM4a(size: number): Uint8Array {
  const bytes = new Uint8Array(size);
  bytes.set([0, 0, 0, 0x1c, 0x66, 0x74, 0x79, 0x70, 0x4d, 0x34, 0x41, 0x20]);
  for (let i = 12; i < size; i += 1) bytes[i] = (i * 7) % 256;
  return bytes;
}
const sha = (b: Uint8Array) => createHash("sha256").update(b).digest("hex");

const META = {
  title: "Integration tone",
  artist: "Origin",
  mood: "white_noise",
  durationSeconds: 60,
  loopable: true,
  sourceUrl: "https://www.o3origin.com/",
  licenceName: "Made by Origin",
  licenceUrl: "https://www.o3origin.com/",
  attributionRequired: false,
  attributionText: "‘Integration tone’ by Origin",
};

async function upload(body: Uint8Array) {
  const presigned = presignMusicUpload(adminId, { kind: "audio", contentType: "audio/mp4", size: body.length });
  const put = await fetch(presigned.uploadUrl, { method: "PUT", headers: presigned.uploadHeaders, body: Buffer.from(body) });
  assert.equal(put.status, 200, "the R2 stand-in accepts exactly the signed type and size");
  return presigned;
}

let studentAuth: Record<string, string> = {};
let otherAuth: Record<string, string> = {};

async function bearer(id: string, role: StoredUser["role"]) {
  const issued = await issueAccessTokenForUser({ id, role, authTokenVersion: 0 } as StoredUser, randomUUID());
  return { authorization: `Bearer ${issued.accessToken}`, [ACCESS_FINGERPRINT_HEADER]: issued.accessFingerprint };
}

async function student(method: string, path: string, body?: unknown, headers = studentAuth) {
  const request = new NextRequest(new URL(`/api/music/${path}`, "https://www.o3origin.com"), {
    method,
    headers: { "content-type": "application/json", ...headers },
    ...(body === undefined ? {} : { body: JSON.stringify(body) }),
  });
  const res = await handleMusicApi(method, request, path.split("/"), "web");
  assert.ok(res, `${method} ${path} matched no route`);
  return res;
}

test("Study Music end to end on a throwaway DB + the R2 stand-in", { skip }, async (t) => {
  if (!(await fakeR2Up())) {
    t.skip("R2 stand-in not reachable (R2_ENDPOINT)");
    return;
  }
  try {
    ({ createTrack, deleteTrack, listAdminTracks, presignMusicUpload, publishTrack, retireTrack, updateTrack } = await import("@/server/music/admin"));
    ({ handleMusicApi } = await import("@/server/music/student-api"));
  } catch (error) {
    t.skip(`run without --conditions=react-server (${error instanceof Error ? error.message.slice(0, 80) : "import failed"})`);
    return;
  }
  process.env.AUTH_JWT_SECRET_CURRENT ??= "MDEyMzQ1Njc4OWFiY2RlZjAxMjM0NTY3ODlhYmNkZWY";
  delete process.env.TEACHER_LAUNCH_STUDY_MUSIC; // dev default: on

  // Schema: twice, idempotent.
  await ensureUserSchema();
  await ensureMusicSchema();
  globalThis.__originMusicSchemaEnsured = false;
  globalThis.__originMusicSchemaPromise = undefined;
  await ensureMusicSchema();
  const ledger = await pool().query(`SELECT 1 FROM app.migrations WHERE id = '20261114_study_music'`);
  assert.equal(ledger.rowCount, 1);

  for (const [id, role] of [[adminId, "admin"], [studentId, "student"], [otherId, "student"]] as const) {
    await pool().query(
      `INSERT INTO origin_users (id, name, email, role, password_hash) VALUES ($1, $2, $3, $4, 'x') ON CONFLICT (id) DO NOTHING`,
      [id, id, `${id}@example.test`, role],
    );
  }
  studentAuth = await bearer(studentId, "student");
  otherAuth = await bearer(otherId, "student");

  // Presign + PUT to the stand-in; a PUT with another size than signed is refused by "R2".
  const audio = fakeM4a(20_000);
  const presigned = presignMusicUpload(adminId, { kind: "audio", contentType: "audio/mp4", size: audio.length });
  const wrong = await fetch(presigned.uploadUrl, { method: "PUT", headers: presigned.uploadHeaders, body: Buffer.from(audio.slice(0, 100)) });
  assert.equal(wrong.status, 403, "R2 refuses a body of another size");
  const wrongType = await fetch(presigned.uploadUrl, { method: "PUT", headers: { "Content-Type": "text/html" }, body: Buffer.from(audio) });
  assert.equal(wrongType.status, 403, "R2 refuses another Content-Type");
  const ok = await fetch(presigned.uploadUrl, { method: "PUT", headers: presigned.uploadHeaders, body: Buffer.from(audio) });
  assert.equal(ok.status, 200);

  // Licence fields are required: no draft without them.
  await expectCode(
    createTrack(adminId, { ...META, sourceUrl: undefined, objectKey: presigned.objectKey, uploadToken: presigned.uploadToken, sha256: sha(audio) }),
    "invalid_track",
  );
  // The DB itself refuses a blank licence field.
  await assert.rejects(
    pool().query(`UPDATE music.tracks SET attribution_text = '' WHERE id = $1`, [randomUUID()]).then(async () => {
      // No row matched; force the CHECK with an INSERT instead.
      await pool().query(
        `INSERT INTO music.tracks (id, title, artist, mood, duration_seconds, object_key, mime_type, size_bytes, sha256, source_url, licence_name, licence_url, attribution_text)
         VALUES ($1, 't', 'a', 'lofi', 60, 'k', 'audio/mp4', 1, $2, 'https://x.org', 'CC0', 'https://x.org', '')`,
        [randomUUID(), "a".repeat(64)],
      );
    }),
    /check constraint/i,
  );

  // Create the draft: the server reads the object back and checks size, type and hash.
  const draft = await createTrack(adminId, { ...META, objectKey: presigned.objectKey, uploadToken: presigned.uploadToken, sha256: sha(audio) });
  assert.equal(draft.status, "draft");
  assert.equal(draft.sizeBytes, audio.length);
  await expectCode(
    createTrack(adminId, { ...META, objectKey: presigned.objectKey, uploadToken: presigned.uploadToken, sha256: sha(audio) }),
    "duplicate_upload",
  );

  // Students don't see drafts.
  let list = await (await student("GET", "tracks")).json();
  assert.deepEqual(list.tracks, []);

  // Edit, then publish.
  const edited = await updateTrack(adminId, draft.id, { title: "Integration tone (edited)", sortOrder: 2 });
  assert.equal(edited.title, "Integration tone (edited)");
  const published = await publishTrack(adminId, draft.id);
  assert.equal(published.status, "published");
  assert.ok(published.publishedAt);
  await expectCode(publishTrack(adminId, draft.id), "not_draft");

  // The student list shows it with its credit.
  list = await (await student("GET", "tracks")).json();
  assert.equal(list.tracks.length, 1);
  assert.equal(list.tracks[0].id, draft.id);
  assert.equal(list.tracks[0].credit.text, META.attributionText);
  assert.equal(list.tracks[0].sha256, sha(audio));
  assert.deepEqual(list.today, { seconds: 0, focusSeconds: 0 });

  // A signed link that really downloads the file, with the stored type.
  const link = await (await student("GET", `tracks/${draft.id}/url`)).json();
  const download = await fetch(link.url);
  assert.equal(download.status, 200);
  assert.equal(download.headers.get("content-type"), "audio/mp4");
  assert.equal(sha(new Uint8Array(await download.arrayBuffer())), sha(audio));
  const range = await fetch(link.url, { headers: { Range: "bytes=0-11" } });
  assert.equal(range.status, 206, "seeking works (Range)");
  assert.equal((await student("GET", `tracks/${randomUUID()}/url`)).status, 404);

  // Listening heartbeats: first one capped at 60 s of wall-clock time.
  const sessionId = randomUUID();
  let res = await student("POST", "listen", { sessionId, trackId: draft.id, seconds: 500, focusSeconds: 500 });
  assert.equal(res.status, 200);
  assert.deepEqual((await res.json()).today, { seconds: 60, focusSeconds: 60 }, "capped at now − started_at + 60");
  // A lower resend never shrinks it.
  res = await student("POST", "listen", { sessionId, trackId: draft.id, seconds: 30, focusSeconds: 10 });
  assert.deepEqual((await res.json()).today, { seconds: 60, focusSeconds: 60 });
  // A session the device started 10 minutes ago (queued offline) keeps its real time.
  const offline = randomUUID();
  res = await student("POST", "listen", {
    sessionId: offline,
    trackId: draft.id,
    seconds: 400,
    focusSeconds: 100,
    startedAt: new Date(Date.now() - 10 * 60_000).toISOString(),
  });
  assert.deepEqual((await res.json()).today, { seconds: 460, focusSeconds: 160 });
  // Over the cap: still bounded by that session's wall-clock time (≈ 600 + 60).
  res = await student("POST", "listen", { sessionId: offline, trackId: draft.id, seconds: 5000, focusSeconds: 0 });
  const today = (await res.json()).today;
  assert.ok(today.seconds - 60 >= 600 && today.seconds - 60 <= 662, `capped: ${today.seconds}`);
  assert.equal(today.focusSeconds, 160, "focus never shrinks");
  // Many fresh sessions backdated to IST midnight can't add up to more than the day had.
  const istMidnight = new Date(Math.floor((Date.now() + 5.5 * 3600_000) / 86_400_000) * 86_400_000 - 5.5 * 3600_000);
  const sinceMidnight = Math.floor((Date.now() - istMidnight.getTime()) / 1000);
  let dayTotal = 0;
  for (let i = 0; i < 4; i++) {
    const r = await student("POST", "listen", {
      sessionId: randomUUID(),
      trackId: draft.id,
      seconds: 86_000,
      focusSeconds: 0,
      startedAt: istMidnight.toISOString(),
    });
    assert.equal(r.status, 200);
    dayTotal = (await r.json()).today.seconds;
  }
  assert.ok(dayTotal <= sinceMidnight + 62, `day total ${dayTotal} within ${sinceMidnight} s since IST midnight (+60)`);
  // Another student can't touch this session.
  assert.equal((await student("POST", "listen", { sessionId, trackId: draft.id, seconds: 1, focusSeconds: 0 }, otherAuth)).status, 404);
  const rows = await pool().query(`SELECT user_id, platform FROM music.listen_sessions WHERE id = $1`, [sessionId]);
  assert.deepEqual(rows.rows, [{ user_id: studentId, platform: "web" }]);

  // Prefs round-trip.
  assert.equal((await student("PUT", "prefs", { defaultMood: "jazz" })).status, 400);
  res = await student("PUT", "prefs", { pauseDuringTests: false });
  assert.deepEqual((await res.json()).prefs, { pauseDuringTests: false, defaultMood: "lofi" });
  res = await student("PUT", "prefs", { defaultMood: "nature" });
  assert.deepEqual((await res.json()).prefs, { pauseDuringTests: false, defaultMood: "nature" });
  assert.deepEqual((await (await student("GET", "tracks")).json()).prefs, { pauseDuringTests: false, defaultMood: "nature" });

  // Admin list: every status, storage total.
  const adminList = await listAdminTracks();
  assert.equal(adminList.tracks.length, 1);
  assert.equal(adminList.storageBytes, audio.length);
  assert.equal(adminList.studentsCanSee, true);

  // Delete refused while published; retire → gone for students, link 404.
  await expectCode(deleteTrack(adminId, draft.id), "published");
  await retireTrack(adminId, draft.id);
  assert.deepEqual((await (await student("GET", "tracks")).json()).tracks, []);
  assert.equal((await student("GET", `tracks/${draft.id}/url`)).status, 404);

  // Delete: row, listening sessions and the object are gone.
  await deleteTrack(adminId, draft.id);
  assert.equal((await pool().query(`SELECT 1 FROM music.tracks WHERE id = $1`, [draft.id])).rowCount, 0);
  assert.equal((await pool().query(`SELECT 1 FROM music.listen_sessions WHERE track_id = $1`, [draft.id])).rowCount, 0);
  assert.equal(await headR2Object({ bucket: process.env.R2_PRIVATE_BUCKET!, objectKey: presigned.objectKey }), null);

  // A second upload: an mp3-typed key with m4a bytes is refused (type check), and its object stays for cleanup.
  const second = await upload(fakeM4a(5000));
  const notMp3 = presignMusicUpload(adminId, { kind: "audio", contentType: "audio/mpeg", size: 5000 });
  await fetch(notMp3.uploadUrl, { method: "PUT", headers: notMp3.uploadHeaders, body: Buffer.from(fakeM4a(5000)) });
  await expectCode(createTrack(adminId, { ...META, objectKey: notMp3.objectKey, uploadToken: notMp3.uploadToken, sha256: sha(fakeM4a(5000)) }), "not_audio");
  void second;

  // Rollback SQL leaves no `music` schema and no ledger row.
  await pool().query(readFileSync(join(root, "src/db/migrations/20261114_study_music.rollback.sql"), "utf8"));
  const schema = await pool().query(`SELECT 1 FROM information_schema.schemata WHERE schema_name = 'music'`);
  assert.equal(schema.rowCount, 0);
  assert.equal((await pool().query(`SELECT 1 FROM app.migrations WHERE id = '20261114_study_music'`)).rowCount, 0);
  // …and the migration file re-creates it cleanly.
  await pool().query(readFileSync(join(root, "src/db/migrations/20261114_study_music.sql"), "utf8"));
  const tables = await pool().query(`SELECT table_name FROM information_schema.tables WHERE table_schema = 'music' ORDER BY 1`);
  assert.deepEqual(tables.rows.map((r) => r.table_name), ["listen_sessions", "tracks", "user_prefs"]);

  await pool().query(`DELETE FROM origin_users WHERE id = ANY($1)`, [[adminId, studentId, otherId]]);
});

test.after(async () => {
  await getUserPostgresPool()?.end().catch(() => undefined);
});
