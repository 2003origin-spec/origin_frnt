/**
 * Study Music against a real Postgres and the local R2 stand-in
 * (V1/STUDY_MUSIC_PLAN.md §11.3). Needs USER_DATABASE_URL (and
 * OGCODE_DATABASE_URL, same DB) pointing at a THROWAWAY database — it ends by
 * running the rollback SQL, which drops the `music` schema. Uploads go to
 * scripts/dev-fake-r2.ts (start it first):
 *
 *   npx tsx scripts/dev-fake-r2.ts &
 *   USER_DATABASE_URL=… OGCODE_DATABASE_URL=… AUTH_JWT_SECRET_CURRENT=… \
 *   R2_ENDPOINT=http://127.0.0.1:9466 R2_ACCESS_KEY_ID=dev R2_SECRET_ACCESS_KEY=dev-secret \
 *   R2_PRIVATE_BUCKET=private-dev R2_BUCKET_NAME=public-dev \
 *   npx tsx --test --test-concurrency=1 tests/integration/study-music.test.ts
 *
 * NOT under --conditions=react-server (the npm test:integration script): the
 * music handlers import src/server/incidents.ts (flag kill switch, rate-limit
 * mode), which imports next/navigation, and that client module can't load with
 * React's server build. Under that condition the test skips with this reason.
 * Skipped too when USER_DATABASE_URL is unset or the R2 stand-in is not reachable.
 * The audio is a small generated byte pattern with an MP4 header: no real audio, nothing downloaded.
 */

